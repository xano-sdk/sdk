/**
 * Every code a failure, a CLI warning or a build diagnostic carries — the one
 * registry `guides/codes.md` is generated from (`npm run codes`).
 *
 * The emitters take these types, not `string`: `new CliError` an
 * {@link ErrorCode}, `warn` / `noteRunWarning` a {@link WarningCode}, a
 * `DiagnosticBag` a {@link DiagnosticCode}. A new code is added here or it
 * does not compile, so the guide cannot miss one; a code listed here that the
 * source no longer emits fails `test/manifest/codes-guide.test.ts`.
 *
 * Match on the code, never on the message text: messages are reworded, codes are not.
 */

